export function getMainsQuestionForTopic(topicId: string, subjectId?: string): MainsSubjectiveQuestion | undefined {
  // 1. Direct topicId match
  const direct = uppcsMainsQuestions.find((q) => q.topicId === topicId);
  if (direct) return direct;

  // 2. Subject match
  if (subjectId) {
    const normSub = subjectId.toLowerCase();
    const bySub = uppcsMainsQuestions.find((q) => q.subjectId.toLowerCase().includes(normSub) || normSub.includes(q.subjectId.toLowerCase()));
    if (bySub) return bySub;
  }

  // 3. Match by paper keywords
  if (topicId) {
    const lower = topicId.toLowerCase();
    if (lower.includes('hindi')) return uppcsMainsQuestions[0];
    if (lower.includes('essay')) return uppcsMainsQuestions[2];
    if (lower.includes('gs-1') || lower.includes('gs-paper-1') || lower.includes('paper-1')) return uppcsMainsQuestions[3];
    if (lower.includes('gs-2') || lower.includes('gs-paper-2') || lower.includes('paper-2')) return uppcsMainsQuestions[4];
    if (lower.includes('gs-3') || lower.includes('gs-paper-3') || lower.includes('paper-3')) return uppcsMainsQuestions[5];
    if (lower.includes('gs-4') || lower.includes('gs-paper-4') || lower.includes('ethics')) return uppcsMainsQuestions[6];
    if (lower.includes('gs-5') || lower.includes('gs-paper-5') || lower.includes('special-1') || lower.includes('special-i')) return uppcsMainsQuestions[7];
    if (lower.includes('gs-6') || lower.includes('gs-paper-6') || lower.includes('special-2') || lower.includes('special-ii')) return uppcsMainsQuestions[8];
  }

  return uppcsMainsQuestions[0];
}
