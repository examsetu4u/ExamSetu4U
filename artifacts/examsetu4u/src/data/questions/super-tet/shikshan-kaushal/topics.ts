export function resolveTopicId(inputTopicId: string): string | null {
  if (!inputTopicId) return null;
  const cleaned = inputTopicId.trim().toLowerCase();

  for (const topic of SHIKSHAN_KAUSHAL_TOPICS) {
    if (topic.id.toLowerCase() === cleaned || topic.canonicalId.toLowerCase() === cleaned) {
      return topic.canonicalId;
    }
    if (topic.aliasIds.some((a) => a.toLowerCase() === cleaned)) {
      return topic.canonicalId;
    }
  }

  // Check if numeric 1..15
  const num = parseInt(cleaned.replace(/[^0-9]/g, ''), 10);
  if (!isNaN(num) && num >= 1 && num <= 15) {
    return `super-tet-teaching-skills-${num}`;
  }

  return null;
}

export function getTopicDefinition(canonicalOrAliasId: string): TopicDefinition | undefined {
  const resolved = resolveTopicId(canonicalOrAliasId);
  if (!resolved) return undefined;
  return SHIKSHAN_KAUSHAL_TOPICS.find((t) => t.canonicalId === resolved);
}
